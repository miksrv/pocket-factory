export const SPRITE_NAMES = Object.keys(SPRITES)

/**
 * The same mixed hash as the tile colour, on its own seed: the mascot and
 * the colour of a name are independent, and the seed keeps the shipped
 * agents on different mascots.
 */
export function spriteFor(name: string): string {
    let h = 6
    for (const ch of name) h = (Math.imul(h, 31) + ch.charCodeAt(0)) >>> 0
    h ^= h >>> 16
    h = Math.imul(h, 0x45d9f3b) >>> 0
    h ^= h >>> 16
    return SPRITE_NAMES[(h >>> 0) % SPRITE_NAMES.length]
}

export function Sprite({ name, sprite }: { name?: string; sprite?: string }) {
    const rows = SPRITES[sprite ?? spriteFor(name ?? '')] ?? SPRITES.ghost
    const width = rows[0].length
    const height = rows.length
    // Pixels are drawn as a path of unit squares in currentColor; the tile sets the colour.
    const path = rows.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `M${x} ${y}h1v1h-1z` : ''))).join('')
    return (
        <svg
            className='sprite'
            viewBox={`0 0 ${width} ${height}`}
            width='1em'
            height='1em'
            aria-hidden
            shapeRendering='crispEdges'
        >
            <path
                d={path}
                fill='currentColor'
            />
        </svg>
    )
}
